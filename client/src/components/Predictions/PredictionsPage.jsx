import { useState, useEffect, useCallback } from 'react';
import { useTranslation } from 'react-i18next';
import { useLanguage } from '../../context/LanguageContext';
import { api } from '../../services/api';
import TeamFlag from '../common/TeamFlag';
import Loading from '../common/Loading';
import ErrorBanner from '../common/ErrorBanner';
import EmptyState from '../common/EmptyState';
import { getTeamName } from '../../utils/helpers';

export default function PredictionsPage() {
  const { t } = useTranslation();
  const { isZh } = useLanguage();
  const [predictions, setPredictions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const fetchData = useCallback(async () => {
    try {
      setError(null);
      const data = await api.getPredictions();
      setPredictions(data.predictions || []);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => { fetchData(); }, [fetchData]);

  if (loading) return <Loading />;
  if (error) return <ErrorBanner message={error} onRetry={fetchData} />;

  // Static prediction data as fallback when API is unavailable
  const displayPredictions = predictions.length > 0 ? predictions : getStaticPredictions();

  return (
    <div className="max-w-4xl mx-auto">
      <div className="flex items-center justify-between mb-6">
        <h1 className="text-2xl font-bold text-white">🤖 Match Predictions</h1>
        <span className="text-xs text-gray-500">
          {predictions.length > 0 ? 'Powered by BSD ML' : 'Community predictions'}
        </span>
      </div>

      {displayPredictions.length > 0 ? (
        <div className="space-y-4">
          {displayPredictions.map((p, idx) => (
            <div key={p.matchId || idx} className="bg-gray-800/40 border border-gray-700 rounded-xl p-4 hover:bg-gray-800/60 transition-colors">
              <div className="flex items-center gap-4">
                <div className="flex items-center gap-2 flex-1 justify-end">
                  <span className="text-sm text-white font-medium">{getTeamName(p.homeCode, isZh) || p.homeTeam || p.home}</span>
                  <TeamFlag code={p.homeCode} name={getTeamName(p.homeCode, isZh) || p.homeTeam} size="sm" />
                </div>

                <div className="text-center">
                  <span className="text-xs text-gray-500">vs</span>
                </div>

                <div className="flex items-center gap-2 flex-1">
                  <TeamFlag code={p.awayCode} name={getTeamName(p.awayCode, isZh) || p.awayTeam} size="sm" />
                  <span className="text-sm text-white font-medium">{getTeamName(p.awayCode, isZh) || p.awayTeam || p.away}</span>
                </div>
              </div>

              {/* Prediction bars */}
              <div className="mt-3">
                <div className="flex justify-between text-xs text-gray-400 mb-1">
                  <span>{getTeamName(p.homeCode, isZh) || p.homeTeam} {p.homeWin || 33}%</span>
                  <span>{isZh ? '平局' : 'Draw'} {p.draw || 34}%</span>
                  <span>{getTeamName(p.awayCode, isZh) || p.awayTeam} {p.awayWin || 33}%</span>
                </div>
                <div className="flex h-3 rounded-full overflow-hidden bg-gray-700">
                  <div
                    className="bg-blue-500 transition-all flex items-center justify-center text-[10px] text-white font-bold"
                    style={{ width: `${p.homeWin || 33}%` }}
                  >
                    {p.homeWin || 33}%
                  </div>
                  <div
                    className="bg-gray-500 transition-all flex items-center justify-center text-[10px] text-white font-bold"
                    style={{ width: `${p.draw || 34}%` }}
                  >
                    {p.draw || 34}%
                  </div>
                  <div
                    className="bg-red-500 transition-all flex items-center justify-center text-[10px] text-white font-bold"
                    style={{ width: `${p.awayWin || 33}%` }}
                  >
                    {p.awayWin || 33}%
                  </div>
                </div>
              </div>

              {p.confidence && (
                <p className="text-xs text-gray-500 mt-2">Confidence: {p.confidence}%</p>
              )}
            </div>
          ))}
        </div>
      ) : (
        <EmptyState icon="🤖" message="No predictions available yet." />
      )}

      <p className="text-xs text-gray-600 text-center mt-6">
        Predictions are generated by machine learning models and are for reference only. Not betting advice.
      </p>
    </div>
  );
}

